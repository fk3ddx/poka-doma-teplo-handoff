using NUnit.Framework;
using UnityEngine;
using Ataka.Editor;

namespace Ataka.Tests
{
    public class RealSizeTests
    {
        GameObject parent, root;
        Mesh mesh;
        RealSize subject;
        [SetUp] public void SetUp()
        {
            parent = new GameObject("MeasurementFixtureParent");
            root = new GameObject("MeasurementFixture");
            root.transform.SetParent(parent.transform, false);
            subject = root.AddComponent<RealSize>();
            subject.reference = "Synthetic metre coordinates for measurement test only";
            // Vertex data only: no game art or furniture is generated by these tests.
            mesh = new Mesh { vertices = new[] {Vector3.zero, new Vector3(.8f, 2f, .1f)} };
            mesh.RecalculateBounds();
            var filter = root.AddComponent<MeshFilter>();
            filter.sharedMesh = mesh;
            subject.parts = new[] {filter};
            subject.expectedMetres = new Vector3(.8f, 2f, .1f);
        }
        [TearDown] public void TearDown()
        { Object.DestroyImmediate(parent); Object.DestroyImmediate(mesh); }

        [Test] public void RotationDoesNotInflateMeasuredDimensions()
        {
            parent.transform.SetPositionAndRotation(new Vector3(20, 4, -30), Quaternion.Euler(15, 70, 0));
            root.transform.localRotation = Quaternion.Euler(0, 42, 0);
            var result = RealSizeAudit.Check(subject);
            Assert.IsTrue(result.passed, result.message);
            Assert.Less(Vector3.Distance(subject.expectedMetres, result.measuredMetres), .0001f);
        }
        [Test] public void ParentScaleIsIncludedAndWrongScaleFails()
        {
            parent.transform.localScale = new Vector3(1, 1.2f, 1);
            var result = RealSizeAudit.Check(subject);
            Assert.IsFalse(result.passed);
            Assert.AreEqual(2.4f, result.measuredMetres.y, .0001f);
        }
        [Test] public void ActualVerticesOverridePaddedBoundsAndNonReadableImportWorks()
        {
            mesh.bounds = new Bounds(Vector3.zero, Vector3.one * 100);
            mesh.UploadMeshData(true);
            Assert.IsFalse(mesh.isReadable);
            Assert.IsTrue(RealSizeAudit.Check(subject).passed);
            Assert.IsFalse(mesh.isReadable, "Audit must not enable Read/Write or edit the imported mesh.");
        }
        [Test] public void SeparatePartOffsetsAreIncluded()
        {
            var second = new GameObject("SecondPart");
            second.transform.SetParent(root.transform, false);
            second.transform.localPosition = new Vector3(.8f, 0, 0);
            var filter = second.AddComponent<MeshFilter>(); filter.sharedMesh = mesh;
            subject.parts = new[] {subject.parts[0], filter};
            var result = RealSizeAudit.Check(subject);
            Assert.IsFalse(result.passed);
            Assert.AreEqual(1.6f, result.measuredMetres.x, .0001f);
        }
        [Test] public void UnknownDimensionsAndMissingPartsCannotPass()
        {
            subject.expectedMetres = Vector3.zero;
            Assert.IsFalse(RealSizeAudit.Check(subject).passed);
            subject.expectedMetres = new Vector3(0, 2, 0);
            Assert.IsTrue(RealSizeAudit.Check(subject).passed, "Height-only reference is allowed.");
            subject.parts = new MeshFilter[0];
            Assert.IsFalse(RealSizeAudit.Check(subject).passed);
        }
        [Test] public void MissingReferenceOrUnboundedToleranceCannotPass()
        {
            subject.reference = "";
            Assert.IsFalse(RealSizeAudit.Check(subject).passed);
            subject.reference = "Measured"; subject.tolerance = 1;
            Assert.IsFalse(RealSizeAudit.Check(subject).passed);
        }
        [Test] public void ExternalMeshCannotBeIncludedByMistake()
        {
            var filter = parent.AddComponent<MeshFilter>(); filter.sharedMesh = mesh;
            subject.parts = new[] {filter};
            Assert.IsFalse(RealSizeAudit.Check(subject).passed);
        }
    }
}
